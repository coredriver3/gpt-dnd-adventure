/** The backend writes rules text in English; this renders it in the UI language, also for saved games. */
export function translateServerText(text: string, language: Language): string {
  if (language === 'en') {
    return text;
  }
  const exact = SERVER_EXACT_DE[text];
  if (exact) {
    return exact;
  }
  for (const [pattern, replacement] of SERVER_PATTERNS_DE) {
    if (pattern.test(text)) {
      return text.replace(pattern, replacement);
    }
  }
  return text;
}
